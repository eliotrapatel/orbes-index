    const notes = r.checks.filter((c) => c.note);
    if (notes.length) {
      L.push('');
      for (const c of notes) L.push(`- *${c.id}:* ${c.note}`);
    }
    L.push('');
    L.push(`Anomaly records: ${r.anomalies.length === 0 ? 'none.' : r.anomalies.map((a) => `${a.type} ${a.severity} ×${a.occurrences}`).join(' · ')}`, '');
