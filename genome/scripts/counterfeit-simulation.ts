  L.push('# ORBES — counterfeit simulation (master spec §27)', '');
  L.push(
    `Generated by \`npx tsx scripts/counterfeit-simulation.ts\` on ${meta.startedAt.toISOString().slice(0, 10)} in ${(meta.durationMs / 1000).toFixed(0)} s${meta.partial ? ' (**partial run**: `--only`)' : ''}. ` +
      'The same scenarios run in CI as `npx vitest run test/simulation` (files `test/simulation/*.test.ts`, scenario code in `test/simulation/scenarios.ts`, harness in `test/simulation/lab.ts`).',
    '',
  );
  L.push(
    `**Result:** ${all.length} checks in ${results.length} scenarios — ${count(results, 'PASS')} PASS, ${count(results, 'GAP')} GAP, ${count(results, 'LIMIT')} LIMIT, ${fails} FAIL. ` +
      (surprises.length === 0 ? 'Every GAP and LIMIT is a documented one (below).' : `**${surprises.length} unexpected outcome(s)** — see the tables.`),
    '',
  );
  if (surprises.length > 0) {
    L.push(`> **Warning:** ${surprises.length} check(s) did not come out as documented (${surprises.map((c) => c.id).join(', ')}). The narrative sections below describe the documented behaviour and may not match this run.`, '');
  }
  L.push('- **PASS** — the expectation of §27 holds.');
  L.push('- **GAP** — §27 expected a different public state; the observed one is what the normative platform contract (`genome/PLATFORM-CONTRACTS.md` §2.4/§2.5) prescribes. Never an AUTHENTIC* answer to a forgery; listed under *Gaps*.');
  L.push('- **LIMIT** — the system behaves as designed but does not catch this counterfeit (a detection limit, e.g. one quiet copy).');
  L.push('- **FAIL** — anything else.', '');

  L.push('## Summary', '');
  L.push('| # | Scenario | Checks | PASS | GAP | LIMIT | FAIL | Photos (decoded) | Verify responses | Time |');
  L.push('|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|');
  for (const r of results) {
    const n = (s: Check['status']) => r.checks.filter((c) => c.status === s).length;
    L.push(
      `| ${r.id} | ${cell(r.title)} | ${r.checks.length} | ${n('PASS')} | ${n('GAP')} | ${n('LIMIT')} | ${n('FAIL')} | ${r.captures.photos} (${r.captures.decoded}) | ${r.responses} | ${(r.durationMs / 1000).toFixed(1)} s |`,
    );
  }
  L.push(`| | **Total** | **${all.length}** | **${count(results, 'PASS')}** | **${count(results, 'GAP')}** | **${count(results, 'LIMIT')}** | **${fails}** | **${photos} (${decoded})** | **${responses}** | |`, '');

  L.push('## Key numbers', '');
  const forgedStates = mergeTallies(results.map((r) => r.forged.states)) || '—';
  L.push(
    `- **Forgeries accepted: ${forgedAuthentic} of ${forged}.** ${forged} verification responses were for byte strings that are not an issued code (edited identity, genome version or signature; codes signed by a foreign, stolen or revoked key; corrupted frames; seeded random codes)${forgedAuthentic === 0 ? ', and none was answered AUTHENTIC*' : ''}. Their states: ${forgedStates}.`,
  );
  const missed = results.filter((r) => r.captures.photos > r.captures.decoded).map((r) => `scenario ${r.id}: ${r.captures.photos - r.captures.decoded}`);
  const onlyDamage = missed.length === 1 && results.find((r) => r.id === 6)?.checks.find((c) => c.id === '6a')?.status === 'PASS' && photos - decoded === 1;
  L.push(
    `- **Phone captures:** ${photos} simulated photographs (${frames} frames, bursts of up to ${BURST_FRAMES}) of genuine, copied, forged and damaged ${ARTIFACT_WIDTH_MM} mm / ${ARTIFACT_DPI} dpi PNG artifacts; ${decoded} decoded (${pct(decoded, photos)}). ` +
      (onlyDamage ? 'The only photo not decoded is the label deliberately damaged beyond Reed-Solomon capacity (6a). ' : missed.length ? `Not decoded: ${missed.join(', ')}. ` : '') +
      `Decoder time per frame: median ${median(decodeMs).toFixed(0)} ms, p95 ${p95(decodeMs).toFixed(0)} ms (this machine, single thread).`,
  );
  L.push(`- **Genome cross-check on genuine prints:** ${genuineScans} camera scans of unaltered genuine artifacts → ${Object.entries(genome).sort().map(([k, v]) => `${k} ${v}`).join(', ')}. **${genome.MISMATCH ?? 0} false GENOME_MISMATCH.** (INCONCLUSIVE = fewer than 6 glyphs read with confidence ≥ 0.5, never flags; NOT_PROVIDED = the decision ended before the cross-check, e.g. a revoked key.)`);
  L.push(`- **Redaction:** ${responses} public responses checked field by field against the contract's allow-list for their state, for internal vocabulary (risk, score, threshold, reasons, anomaly types), raw product/code statuses and the world's secrets (row ids, payload hashes, claim codes, account ids): ${redaction.every((c) => c.status === 'PASS') ? '**0 leaks**' : '**LEAKS FOUND**'}. States covered: ${states.join(', ')} (${states.length} of 9).`);
